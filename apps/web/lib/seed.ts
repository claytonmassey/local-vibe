function toDraft(item: PlanItem): PlanDraft {
  return { groupId: item.groupId, windowId: item.windowId, date: item.date, status: item.status, kind: item.kind };
}

function buildPlan(today: string): { planItems: PlanItem[]; drafts: Draft[] } {
  const published = groups.filter((group) => group.listingStatus === "published");
  const planItems: PlanItem[] = [];
  const week = weekDates(today);

  const pushOpp = (date: string, status: "planned" | "done") => {
    const opportunity = opportunitiesForDate(published, date, planItems.map(toDraft))[0];
    if (!opportunity) return null;
    const item: PlanItem = {
      id: `plan_${date}`,
      businessId: "biz_sara",
      editionId: "ed_founding",
      groupId: opportunity.group.id,
      windowId: opportunity.window.id,
      date,
      startLocal: opportunity.window.startLocal,
      endLocal: opportunity.window.endLocal,
      timeZone: ZONE,
      kind: "verified",
      status,
      notes: "",
      revision: 1,
    };
    planItems.push(item);
    return item;
  };

  const past = week.filter((date) => date < today).reverse();
  for (const date of past) {
    if (pushOpp(date, "done")) break;
  }

  let focus = pushOpp(today, "planned");
  if (!focus) {
    focus = {
      id: `plan_${today}`,
      businessId: "biz_sara",
      editionId: "ed_founding",
      groupId: "grp_magnolia",
      windowId: null,
      date: today,
      startLocal: null,
      endLocal: null,
      timeZone: ZONE,
      kind: "personal_reminder",
      status: "planned",
      notes: "Block an hour to choose three verified slots for the coming week.",
      revision: 1,
    };
    planItems.push(focus);
  }

  for (const date of week.filter((date) => date > today)) {
    if (pushOpp(date, "planned")) break;
  }

  const theme = themeForDate(focus.date);
  const group = groups.find((item) => item.id === focus.groupId)!;
  const composed = composeDraft({
    businessName: "Wild Orchid Photography",
    category: "Photography",
    city: "Magnolia",
    zip: "77354",
    offerings: "Family sessions and brand portraits at the Magnolia studio.",
    tone: "Friendly",
    themeName: theme.name,
    themePrompt: theme.prompt,
    talkingPoints: "",
    groupName: focus.kind === "verified" ? group.name : null,
    conditions: focus.kind === "verified" ? group.windows.find((item) => item.id === focus.windowId)?.conditions ?? null : null,
  });

  const drafts: Draft[] = [
    {
      id: "drf_seed",
      businessId: "biz_sara",
      planItemId: focus.id,
      groupId: focus.kind === "verified" ? focus.groupId : null,
      title: composed.title,
      body: composed.body,
      reminders: composed.reminders,
      revision: 1,
      createdAt: `${today}T15:00:00.000Z`,
    },
  ];
  return { planItems, drafts };
}

